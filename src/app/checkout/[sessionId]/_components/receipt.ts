import { formatPeso, getBreakdown, type CheckoutSession } from "../../_data/sessions";
import type { ContactDetails, PaymentAttempt } from "./types";

const receiptTimeFormatter = new Intl.DateTimeFormat("en-GB", {
  day: "numeric",
  month: "short",
  year: "numeric",
  hour: "numeric",
  minute: "2-digit",
  hour12: true,
});

/**
 * Builds a self-contained HTML receipt the customer can save or print.
 *
 * It carries a prominent "prototype, not a valid receipt" banner on
 * purpose: no payment actually happened here, so the file must not be
 * mistakable for a genuine financial record once it's off this page and
 * sitting in someone's downloads folder.
 */
export function buildReceiptHtml({
  session,
  attempt,
  methodName,
  contact,
}: {
  session: CheckoutSession;
  attempt: PaymentAttempt;
  methodName: string;
  contact: ContactDetails;
}): string {
  const { subtotal, fee, total } = getBreakdown(session);
  const when = receiptTimeFormatter.format(new Date(attempt.timestamp));

  const row = (label: string, value: string) =>
    `<tr><td class="l">${escapeHtml(label)}</td><td class="v">${escapeHtml(value)}</td></tr>`;

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Receipt ${escapeHtml(attempt.reference)} — ${escapeHtml(session.merchantName)}</title>
<style>
  :root { color-scheme: light; }
  body { margin: 0; padding: 40px 24px; background: #f4f5f6;
    font-family: Roboto, -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; color: #141618; }
  .sheet { max-width: 560px; margin: 0 auto; background: #fff; border-radius: 14px; padding: 40px; }
  .note { background: #f7ec30; color: #141618; font-size: 12px; font-weight: 700; letter-spacing: .06em;
    text-transform: uppercase; padding: 10px 14px; border-radius: 8px; margin-bottom: 32px; }
  h1 { font-size: 22px; margin: 0 0 4px; letter-spacing: -.02em; }
  .sub { color: #6b7075; font-size: 14px; margin: 0 0 28px; }
  .total { font-size: 34px; font-weight: 900; letter-spacing: -.02em; margin: 0 0 4px; }
  .totall { font-size: 11px; font-weight: 700; letter-spacing: .06em; text-transform: uppercase;
    color: #6b7075; margin: 0 0 24px; }
  table { width: 100%; border-collapse: collapse; }
  td { padding: 9px 0; font-size: 14px; vertical-align: top; }
  td.l { color: #6b7075; }
  td.v { text-align: right; font-weight: 500; }
  .div { height: 1px; background: #e6e8ea; margin: 20px 0; }
  .foot { margin-top: 32px; font-size: 12px; color: #6b7075; line-height: 1.6; }
  @media print { body { background: #fff; padding: 0; } .sheet { padding: 0; } }
</style>
</head>
<body>
  <div class="sheet">
    <div class="note">Prototype — not a valid receipt. No payment was processed.</div>

    <h1>${escapeHtml(session.merchantName)}</h1>
    <p class="sub">${escapeHtml(session.description)}</p>

    <p class="totall">Amount paid</p>
    <p class="total">${escapeHtml(formatPeso(total))}</p>

    <div class="div"></div>

    <table>
      ${row("Reference", attempt.reference)}
      ${row("Date & time", when)}
      ${row("Payment method", methodName)}
      ${row("Billed to", contact.name || "—")}
      ${row("Email", contact.email || "—")}
    </table>

    <div class="div"></div>

    <table>
      ${row("Subtotal", formatPeso(subtotal))}
      ${row("Processing fee", formatPeso(fee))}
      ${row("Total", formatPeso(total))}
    </table>

    <p class="foot">
      Payments processed by Diliman Labs.<br />
      This document was generated by a prototype checkout for demonstration
      purposes and has no financial or legal effect.
    </p>
  </div>
</body>
</html>`;
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** Triggers a browser download of the receipt — same Blob + temporary
 * anchor approach the Ops Console's ledger CSV export uses. */
export function downloadReceipt(html: string, reference: string): void {
  const blob = new Blob([html], { type: "text/html;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = `receipt-${reference}.html`;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}
